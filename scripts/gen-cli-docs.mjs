#!/usr/bin/env node
// Renders `loadout --help` and every subcommand's `--help` into docs/cli.md,
// so the CLI reference always matches clap. Run from the repository root:
//
//   node scripts/gen-cli-docs.mjs            # builds the CLI, writes docs/cli.md
//   node scripts/gen-cli-docs.mjs --check    # exits 1 when docs/cli.md is stale
//   node scripts/gen-cli-docs.mjs --bin PATH # uses an already built `loadout`
//
// Hidden commands (git-credential) do not appear in clap's command lists, so
// they are not documented here. `loadout exec` parses its own arguments
// (it must never write to stdout) and prints its usage on stderr instead.

import { execFileSync, spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const check = args.includes("--check");
const binIndex = args.indexOf("--bin");
const out = join("docs", "cli.md");

let bin;
if (binIndex >= 0) {
  bin = args[binIndex + 1];
} else {
  execFileSync("cargo", ["build", "--quiet", "-p", "agent-loadout"], { stdio: "inherit" });
  bin = join("target", "debug", process.platform === "win32" ? "loadout.exe" : "loadout");
}

function help(path) {
  // A fixed terminal width keeps the wrapped help text identical across machines.
  const run = spawnSync(bin, [...path, "--help"], {
    encoding: "utf8",
    env: { ...process.env, COLUMNS: "100", NO_COLOR: "1" },
  });
  const text = run.stdout.trim() !== "" ? run.stdout : run.stderr;
  if (text.trim() === "") throw new Error(`no help text for ${path.join(" ")}`);
  return text
    .replace(/\r\n/g, "\n")
    .replace(/^loadout-exec: usage: /, "Usage: ")
    .replace(/^Usage: loadout\.exe/m, "Usage: loadout")
    .trimEnd();
}

/** Subcommand names listed under `Commands:` (skipping clap's `help`). */
function subcommands(text) {
  const lines = text.split("\n");
  const start = lines.findIndex((line) => line.trim() === "Commands:");
  if (start < 0) return [];
  const names = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === "") break;
    const match = /^  (\S+)/.exec(line);
    if (match && match[1] !== "help") names.push(match[1]);
  }
  return names;
}

const sections = [];
function walk(path) {
  const text = help(path);
  sections.push({ path, text });
  for (const name of subcommands(text)) walk([...path, name]);
}
walk([]);

const anchor = (path) => ["loadout", ...path].join("-");
const lines = [
  "# CLI reference",
  "",
  "<!-- Generated by scripts/gen-cli-docs.mjs from the clap help text. Do not edit by hand:",
  "     run `node scripts/gen-cli-docs.mjs` after changing the CLI. -->",
  "",
  "Every `loadout` command with its options, as printed by `--help`. The global",
  "options `--home`, `--json` and `--yes` work with every command. Exit codes",
  "and task-oriented examples are in the [user guide](user-guide.md#the-command-line).",
  "",
  "## Commands",
  "",
  ...sections.map(
    ({ path }) => `${"  ".repeat(Math.max(path.length - 1, 0))}- [\`${["loadout", ...path].join(" ")}\`](#${anchor(path)})`,
  ),
  "",
];
for (const { path, text } of sections) {
  lines.push(`## \`${["loadout", ...path].join(" ")}\``);
  lines.push("", "```text", text, "```", "");
}
const rendered = lines.join("\n");

if (check) {
  const current = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== rendered) {
    console.error(`${out} is out of date; run node scripts/gen-cli-docs.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(out, rendered);
  console.log(`wrote ${out} (${sections.length} commands)`);
}
